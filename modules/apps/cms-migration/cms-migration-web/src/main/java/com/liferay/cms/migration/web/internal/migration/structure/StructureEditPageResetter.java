package com.liferay.cms.migration.web.internal.migration.structure;

import com.liferay.cms.migration.web.internal.migration.CMSMigrationContext;
import com.liferay.layout.constants.LayoutTypeSettingsConstants;
import com.liferay.layout.page.template.model.LayoutPageTemplateEntry;
import com.liferay.layout.page.template.service.LayoutPageTemplateEntryLocalService;
import com.liferay.object.model.ObjectDefinition;
import com.liferay.petra.string.StringBundler;
import com.liferay.portal.kernel.exception.PortalException;
import com.liferay.portal.kernel.model.Group;
import com.liferay.portal.kernel.model.GroupConstants;
import com.liferay.portal.kernel.model.Layout;
import com.liferay.portal.kernel.service.GroupLocalService;
import com.liferay.portal.kernel.service.LayoutLocalService;
import com.liferay.portal.kernel.util.GetterUtil;
import com.liferay.portal.kernel.util.Portal;

/**
 * @author Jessyca Ferreira
 */
public class StructureEditPageResetter {

	public StructureEditPageResetter(
		GroupLocalService groupLocalService,
		LayoutLocalService layoutLocalService,
		LayoutPageTemplateEntryLocalService layoutPageTemplateEntryLocalService,
		Portal portal) {

		_groupLocalService = groupLocalService;
		_layoutLocalService = layoutLocalService;
		_layoutPageTemplateEntryLocalService =
			layoutPageTemplateEntryLocalService;
		_portal = portal;
	}

	public void reset(CMSMigrationContext cmsMigrationContext) {
		Group group = _groupLocalService.fetchGroup(
			cmsMigrationContext.getCompanyId(), GroupConstants.CMS);

		if (group == null) {
			return;
		}

		for (ObjectDefinition objectDefinition :
				cmsMigrationContext.getObjectDefinitions(
				).values()) {

			try {
				_reset(cmsMigrationContext, group, objectDefinition);
			}
			catch (PortalException portalException) {
				cmsMigrationContext.getCMSMigrationReport(
				).addWarning(
					StringBundler.concat(
						"Unable to reset the edit page of the structure ",
						objectDefinition.getExternalReferenceCode(), ": ",
						portalException.getMessage())
				);
			}
		}
	}

	private void _deleteLayoutPageTemplateEntry(
			long groupId, String layoutPageTemplateEntryKey)
		throws PortalException {

		LayoutPageTemplateEntry layoutPageTemplateEntry =
			_layoutPageTemplateEntryLocalService.fetchLayoutPageTemplateEntry(
				groupId, layoutPageTemplateEntryKey);

		if (layoutPageTemplateEntry != null) {
			_layoutPageTemplateEntryLocalService.deleteLayoutPageTemplateEntry(
				layoutPageTemplateEntry);
		}
	}

	private void _reset(
			CMSMigrationContext cmsMigrationContext, Group group,
			ObjectDefinition objectDefinition)
		throws PortalException {

		long classNameId = _portal.getClassNameId(
			objectDefinition.getClassName());

		_deleteLayoutPageTemplateEntry(
			group.getGroupId(), "LFR_CMS_COMPARE_" + classNameId);
		_deleteLayoutPageTemplateEntry(
			group.getGroupId(), "LFR_CMS_TRANSLATION_" + classNameId);

		LayoutPageTemplateEntry layoutPageTemplateEntry =
			_layoutPageTemplateEntryLocalService.
				fetchDefaultLayoutPageTemplateEntry(
					group.getGroupId(), classNameId, 0);

		if (layoutPageTemplateEntry == null) {
			return;
		}

		Layout draftLayout = _layoutLocalService.fetchDraftLayout(
			layoutPageTemplateEntry.getPlid());

		if ((draftLayout == null) ||
			!GetterUtil.getBoolean(
				draftLayout.getTypeSettingsProperty(
					LayoutTypeSettingsConstants.KEY_AUTOGENERATED))) {

			cmsMigrationContext.getCMSMigrationReport(
			).addWarning(
				StringBundler.concat(
					"Kept the customized edit page of the structure ",
					objectDefinition.getExternalReferenceCode(),
					", so reset it in the structure builder if it is missing ",
					"fields that the migration added or deleted")
			);

			return;
		}

		_layoutPageTemplateEntryLocalService.deleteLayoutPageTemplateEntry(
			layoutPageTemplateEntry);
	}

	private final GroupLocalService _groupLocalService;
	private final LayoutLocalService _layoutLocalService;
	private final LayoutPageTemplateEntryLocalService
		_layoutPageTemplateEntryLocalService;
	private final Portal _portal;

}